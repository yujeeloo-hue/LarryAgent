import { chatCompletionOnce } from "../llm/openaiCompatibleClient.js";
import { noReasoningExtraBody } from "../llm/reasoningDisable.js";
import type { OpenAiCompatibleClientConfig } from "../llm/types.js";
import { agentLogError, agentLogInfo, agentLogWarn } from "../logging/agentLog.js";
import { getDefaultCommitMessagePrompt } from "../settings/promptDefaults.js";
import type { CommitContext } from "./types.js";
import { fallbackCommitMessage } from "./workingTree.js";

const FALLBACK_PROMPT = `Write a concise git commit message (imperative subject, optional short body). Output the message only.`;

export type GenerateCommitMessageInput = {
  workspacePath: string;
  context: CommitContext;
  client: OpenAiCompatibleClientConfig;
  signal?: AbortSignal;
};

/** Normalize model output into a usable commit message body. */
export function sanitizeCommitMessage(raw: string): string | null {
  let text = raw.trim();
  if (!text) return null;

  const fence = text.match(/```(?:\w+)?\s*([\s\S]*?)```/);
  if (fence?.[1]) {
    text = fence[1].trim();
  }

  text = text
    .replace(/^(?:commit\s*message|message|subject)\s*[:：]\s*/i, "")
    .replace(/^["'`“”‘’]+|["'`“”‘’]+$/g, "")
    .trim();

  if (!text) return null;
  // Soft cap to avoid absurd paste-backs.
  if (text.length > 4000) {
    text = text.slice(0, 4000).trimEnd();
  }
  return text;
}

export type GeneratedCommitMessage = {
  message: string;
  /** "llm" when generated by the model; "fallback" when the deterministic placeholder. */
  source: "llm" | "fallback";
};

/**
 * Generate a commit message from truncated status/diff via non-streaming LLM.
 * On failure returns a deterministic fallback (never throws for LLM errors);
 * callers surface {@link GeneratedCommitMessage.source} so the UI can hint.
 *
 * Reasoning is disabled via provider switches and no temperature is ever set —
 * Kimi K-series models forbid it (docs + "only 1 / only 0.6 is allowed" 400s),
 * and every other provider is fine with its default.
 */
export async function generateCommitMessage(
  input: GenerateCommitMessageInput,
): Promise<GeneratedCommitMessage> {
  const fallback = fallbackCommitMessage({
    isRepo: true,
    insertions: input.context.insertions,
    deletions: input.context.deletions,
    dirtyFileCount: input.context.dirtyFileCount,
    // Fallback message copy never mentions the ahead count.
    aheadCount: 0,
    behindCount: 0,
  });

  const systemPrompt =
    getDefaultCommitMessagePrompt().trim() || FALLBACK_PROMPT;
  const userContent = input.context.status.trim();
  if (!userContent) {
    return { message: fallback, source: "fallback" };
  }

  agentLogInfo("git.commit_message.start", {
    workspacePath: input.workspacePath,
    contextChars: userContent.length,
    dirtyFileCount: input.context.dirtyFileCount,
  });

  try {
    const result = await chatCompletionOnce(input.client, {
      messages: [
        { role: "system", content: systemPrompt },
        { role: "user", content: userContent },
      ],
      ...(input.signal ? { signal: input.signal } : {}),
      meta: {
        purpose: "commit_message",
      },
      extraBody: noReasoningExtraBody(input.client.baseUrl),
    });

    const message = sanitizeCommitMessage(result.content);
    if (!message) {
      agentLogWarn("git.commit_message.parse_failed", {
        workspacePath: input.workspacePath,
        preview: result.content.slice(0, 240),
      });
      return { message: fallback, source: "fallback" };
    }

    agentLogInfo("git.commit_message.ok", {
      workspacePath: input.workspacePath,
      messageChars: message.length,
    });
    return { message, source: "llm" };
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    agentLogError("git.commit_message.error", {
      workspacePath: input.workspacePath,
      message,
    });
    return { message: fallback, source: "fallback" };
  }
}
