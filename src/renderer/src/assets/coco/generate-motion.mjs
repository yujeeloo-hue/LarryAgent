import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const directory = resolve(import.meta.dirname);
const output = `${directory}/running`;
const names = ["emerald", "ocean", "sky", "iris", "orchid", "coral", "sunrise", "aurora"];
const sources = names.map((name, i) => readFileSync(`${directory}/palettes/mate-palette-${String(i + 1).padStart(2, "0")}-${name}-16.svg`, "utf8"));
const colors = sources.map(source => [...source.matchAll(/<stop\b[^>]*stop-color="([^"]+)"/g)].map(match => match[1]));
if (colors.some(stops => stops.length !== colors[0].length)) throw new Error("Coco palettes must share the same gradient stops");

const CYCLE_S = 12.8;
const segment = 100 / names.length;
// Layer 0 is emerald; layers 1..7 fade in over their segment on top of the
// previous one, and layer 8 repeats emerald so the loop restart is seamless.
// An opaque palette under the next one at opacity t equals the sRGB stop-color
// interpolation the palettes describe. Each layer switches off once the layer
// above it is fully opaque, so at most two bitmaps are drawn per frame.
const OFF = 0.01;
const fades = names.map((_, i) => i + 1).map(layer => {
  const start = (layer - 1) * segment, end = layer * segment, covered = end + segment;
  const hidden = start === 0 ? "0%" : `0%,${start}%`;
  const shown = end >= 100 ? "100%{opacity:1}"
    : covered >= 100 ? `${end}%,100%{opacity:1}`
    : `${end}%,${covered}%{opacity:1}${covered + OFF}%,100%{opacity:0}`;
  return `@keyframes coco-fade-${layer}{${hidden}{opacity:0;animation-timing-function:ease-in-out}${shown}}`;
}).join("");
const base = `@keyframes coco-fade-0{0%,${segment}%{opacity:1}${segment + OFF}%,100%{opacity:0}}`;
writeFileSync(`${directory}/motion.css`, `/* Generated by generate-motion.mjs from the eight approved palettes. */\n.coco-icon-palette{opacity:0;animation-duration:${CYCLE_S}s;animation-timing-function:linear;animation-iteration-count:infinite;animation-delay:var(--coco-motion-delay,0s)}\n${base}${fades}\n`);

// Field bitmap edge in device pixels: 3× artwork box × 2 DPR × 1.5 UI zoom for
// the largest icon each artwork serves (16px art ≤ 16px; 32px art up to 64px).
const RASTER_PX = { 16: 16 * 3 * 2 * 1.5, 32: 64 * 3 * 2 * 1.5 };
const scratch = mkdtempSync(join(tmpdir(), "coco-motion-"));
const jobs = [];
rmSync(output, { recursive: true, force: true });
mkdirSync(output);
for (const size of [16, 32]) {
  const source = readFileSync(`${directory}/palettes/mate-palette-01-emerald-${size}.svg`, "utf8");
  const band = source.match(/<clipPath id="band"><path d="([^"]+)" clip-rule="evenodd" \/><\/clipPath>/);
  if (!band) throw new Error(`Missing band clip path in the ${size}px artwork`);
  // The silhouette stays a vector clip path (spun by cocoIcon.css) for crisp edges.
  writeFileSync(`${output}/band-${size}.txt`, `${band[1]}\n`);
  // Static color fields: 3× the artwork box so every rotation of the silhouette
  // stays covered; the blur is baked into each image.
  const field = source
    .replace(/<title>.*?<\/title>/, "")
    .replace(/width="\d+" height="\d+" viewBox="0 0 24 24"/, `width="${size * 3}" height="${size * 3}" viewBox="-12 -12 48 48"`)
    .replace(band[0], "")
    .replace('<linearGradient id="base" x2="1" y2="1">', '<linearGradient id="base" gradientUnits="userSpaceOnUse" x2="24" y2="24">')
    .replace('<rect width="24" height="24"', '<rect x="-12" y="-12" width="48" height="48"')
    .replace('</defs>', '<filter id="coco-fill" filterUnits="userSpaceOnUse" x="-12" y="-12" width="48" height="48" color-interpolation-filters="sRGB"><feGaussianBlur stdDeviation=".8" /></filter></defs>')
    .replace('<g transform="translate(0 .74)" clip-path="url(#band)">', '<g transform="translate(0 .74)"><g filter="url(#coco-fill)">')
    .replace('</g></svg>', '</g></g></svg>');
  if (field.includes("clip-path") || !field.includes('filter="url(#coco-fill)"')) throw new Error(`Unexpected ${size}px artwork structure`);
  names.forEach((_, palette) => {
    let index = 0;
    const painted = field.replace(/(<stop\b[^>]*stop-color=")[^"]+"/g, (_, head) => `${head}${colors[palette][index++]}"`);
    if (index !== colors[palette].length) throw new Error(`The ${size}px artwork has ${index} stops, palettes have ${colors[palette].length}`);
    const svg = `${scratch}/fill-${size}-${palette}.svg`;
    writeFileSync(svg, painted);
    jobs.push({ svg, out: `${output}/fill-${size}-${palette}.png`, px: RASTER_PX[size] });
  });
}
// Rasterize with the app's own Chromium so the PNGs match the runtime renderer.
const jobsFile = `${scratch}/jobs.json`;
writeFileSync(jobsFile, JSON.stringify(jobs));
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
const electron = resolve(directory, "../../../../../node_modules/.bin/electron");
execFileSync(electron, [`${directory}/rasterize-motion.cjs`, jobsFile], { env, stdio: "inherit" });
rmSync(scratch, { recursive: true, force: true });
console.log("Generated CoCo animation from the eight approved palettes (12.8s cycle)");
