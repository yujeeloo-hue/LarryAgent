function clangdJobsForWorkspace(
  unreal: boolean,
  cpuCount: number,
  availableMemoryBytes = 0,
  configuredJobs = process.env.JB_CLANGD_JOBS,
  speed: ClangdIndexingSpeed = "normal",
): number {
  const cpu = Number.isFinite(cpuCount) ? Math.max(1, Math.floor(cpuCount)) : 4;
  if (configuredJobs && /^[1-9]\d*$/.test(configuredJobs)) {
    return Math.min(cpu, Number(configuredJobs));
  }
  const cpuBudget = speed === "full" ? cpu : Math.max(1, Math.floor(cpu / 2));
  const estimatedBytesPerWorker = (unreal ? 3 : 0.5) * 1024 ** 3;
  const memoryBudget = Number.isFinite(availableMemoryBytes) && availableMemoryBytes > 0
    ? Math.max(1, Math.floor(availableMemoryBytes * (speed === "full" ? 0.75 : 0.5) / estimatedBytesPerWorker))
    : unreal ? 2 : 4;
  return Math.min(speed === "full" ? cpu : unreal ? 4 : 8, cpuBudget, memoryBudget);
}

