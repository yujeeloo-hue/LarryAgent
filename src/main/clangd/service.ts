function isPidAlive(pid: number): boolean {
  if (!Number.isInteger(pid) || pid <= 0) return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch (err) {
    return (err as NodeJS.ErrnoException)?.code === "EPERM";
  }
}

function sweepOrphanPchDirsOnce(): void {
  if (orphanPchSwept) return;
  orphanPchSwept = true;
  const rootTmp = tmpdir();
  const base = join(rootTmp, PCH_TEMP_ROOT_NAME);
  void readdirAsync(base, { withFileTypes: true })
    .then(async (entries) => {
      for (const entry of entries) {
        if (!entry.isDirectory()) continue;
        const m = /^(\d+)-/.exec(entry.name);
        const ownerPid = m ? Number(m[1]) : NaN;
        if (Number.isInteger(ownerPid) && (ownerPid === process.pid || isPidAlive(ownerPid))) {
          continue;
        }
        await rmAsync(join(base, entry.name), { recursive: true, force: true }).catch(() => {});
      }
    })
    .catch(() => {});
}

